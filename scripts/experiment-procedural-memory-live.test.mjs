import test from "node:test";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
for (const format of ["sse", "json", "seeded"])
  test(`live driver enforces its global budget and observes ${format} responses`, async () => {
    const directory = await fs.mkdtemp(
        path.join(os.tmpdir(), "liminal-budget-"),
      ),
      output = path.join(directory, "run");
    let requests = 0;
    const server = createServer(async (req, res) => {
      requests++;
      for await (const _ of req) {
      }
      if (format === "json") {
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(
          JSON.stringify({
            id: "mock-json",
            choices: [
              {
                message: { role: "assistant", content: "No file generated." },
                finish_reason: "stop",
              },
            ],
            usage: { prompt_tokens: 100, completion_tokens: 20, cost: 0.0001 },
          }),
        );
        return;
      }
      res.writeHead(200, { "Content-Type": "text/event-stream" });
      res.end(
        "data: " +
          JSON.stringify({
            id: "mock",
            choices: [
              {
                index: 0,
                delta: {
                  content: "No result generated by local budget probe.",
                },
                finish_reason: "stop",
              },
            ],
          }) +
          "\n\ndata: [DONE]\n\n",
      );
    });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    try {
      const child = spawn(
        process.execPath,
        [
          "scripts/experiment-procedural-memory-live.mjs",
          "--live",
          "--model",
          "local-budget-probe",
          "--base-url",
          `http://127.0.0.1:${server.address().port}/v1`,
          "--max-calls",
          "1",
          "--max-seconds",
          "8",
          "--max-usd",
          "1",
          "--input-usd-per-million",
          "1",
          "--output-usd-per-million",
          "1",
          "--output",
          output,
          ...(format === "seeded"
            ? [
                "--scripted-acquisition",
                "--arm-order",
                "D",
                "--phases",
                "drift",
              ]
            : []),
        ],
        {
          windowsHide: true,
          env: { ...process.env, AGENT_API_KEY: "local-mock-only" },
          stdio: ["ignore", "pipe", "pipe"],
        },
      );
      let log = "";
      child.stdout.on("data", (b) => (log += b));
      child.stderr.on("data", (b) => (log += b));
      const timer = setTimeout(() => child.kill(), 15000);
      const code = await new Promise((resolve) => child.once("exit", resolve));
      clearTimeout(timer);
      assert.equal(code, 0, log);
      const result = JSON.parse(
        await fs.readFile(path.join(output, "live-results.json"), "utf8"),
      );
      assert.equal(requests, 1);
      assert.equal(result.calls, 1);
      assert(result.reservedUsd <= 1);
      if (format === "json") {
        assert.equal(result.requests[0].generationId, "mock-json");
        assert.equal(result.requests[0].usage.prompt_tokens, 100);
        assert(
          Math.abs(result.reservedUsd - 0.00012) < 1e-10,
          "Completed usage must settle the conservative reservation at declared maximum rates",
        );
      }
      assert(result.elapsedMs < 13000);
      if (format === "seeded") {
        const acquired = result.outcomes.find((o) => o.phase === "acquire");
        assert(acquired.correct);
        assert.equal(acquired.controller, "matched_scripted_offline");
        assert.equal(acquired.providerCalls, 0);
        assert.equal(
          result.outcomes.find((o) => o.phase === "drift").controller,
          "live_model",
        );
      } else
        assert(
          result.outcomes.every((o) => !o.correct),
          "A success claim must not fool the external file oracle",
        );
    } finally {
      server.closeAllConnections();
      server.close();
      assert.equal(path.dirname(directory), path.resolve(os.tmpdir()));
      await fs.rm(directory, {
        recursive: true,
        force: true,
        maxRetries: 10,
        retryDelay: 20,
      });
    }
  });
